/* ── Service pages ──────────────────────────────────────────────────── */

export interface ServiceStep {
  title: string;
  /** Shown as a tag beside the title, e.g. "שבוע 1 עד 3". */
  duration?: string;
  body: string;
}

/** A service page is a run of blocks between its hero and its CTA. */
export type ServiceBlock =
  | { kind: "steps"; title: string; items: readonly ServiceStep[] }
  | { kind: "list"; title: string; items: readonly string[] }
  | { kind: "text"; title: string; paragraphs: readonly string[]; band?: boolean; chips?: readonly string[] }
  | { kind: "story"; title: string; story: Story }
  | { kind: "faq"; title: string; items: readonly Faq[] };

export interface ServicePage {
  path: string;
  /** Schema.org Service name. */
  serviceName: string;
  meta: { title: string; description: string };
  crumbs: readonly Crumb[];
  title: string;
  intro: readonly string[];
  blocks: readonly ServiceBlock[];
  cta: { primary: LinkItem; secondary: LinkItem };
}

